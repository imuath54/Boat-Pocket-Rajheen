// Header scroll effect
function initHeaderScroll() {
    const header = document.querySelector('.header');
    if (header) {
        window.addEventListener('scroll', () => {
            if (window.scrollY > 100) {
                header.style.background = 'rgba(255, 255, 255, 0.98)';
                header.style.boxShadow = '0 2px 20px rgba(0, 0, 0, 0.1)';
            } else {
                header.style.background = 'rgba(255, 255, 255, 0.95)';
                header.style.boxShadow = 'none';
            }
        });
    }
}

// Initialize everything when DOM is loaded
document.addEventListener('DOMContentLoaded', function() {
    // Load saved language preference
    const savedLang = localStorage.getItem('preferredLanguage');
    if (savedLang) {
        document.getElementById('languageSelect').value = savedLang;
        translatePage();
    }
    
    // Initialize all features
    initChart();
    initSmoothScrolling();
    initMobileNav();
    initContactForm();
    initPricingPlans();
    initHeaderScroll();
    
    // Add animation on scroll
    const observerOptions = {
        threshold: 0.1,
        rootMargin: '0px 0px -50px 0px'
    };
    
    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.style.opacity = '1';
                entry.target.style.transform = 'translateY(0)';
            }
        });
    }, observerOptions);
    
    // Observe elements for animation
    document.querySelectorAll('.feature-card, .pricing-card, .testimonial-card, .step').forEach(el => {
        el.style.opacity = '0';
        el.style.transform = 'translateY(30px)';
        el.style.transition = 'opacity 0.6s ease, transform 0.6s ease';
        observer.observe(el);
    });
});

// Real-time updates simulation
function simulateRealTimeUpdates() {
    const rsiElement = document.querySelector('.trade-info .trade-item:nth-child(2) span:last-child');
    const successRateElement = document.querySelector('.success-rate');
    
    if (rsiElement && successRateElement) {
        setInterval(() => {
            // Update RSI
            const newRSI = (Math.random() * 100).toFixed(1);
            rsiElement.textContent = newRSI;
            
            // Update success rate
            const newRate = (88 + Math.random() * 4).toFixed(1);
            successRateElement.textContent = newRate + '%';
            
            // Update signal
            const signals = ['شراء', 'بيع', 'انتظار'];
            const signalElement = document.querySelector('.signal-buy');
            if (signalElement) {
                const randomSignal = signals[Math.floor(Math.random() * signals.length)];
                signalElement.textContent = randomSignal;
                signalElement.className = randomSignal === 'شراء' ? 'signal-buy' : 
                                         randomSignal === 'بيع' ? 'signal-sell' : 'signal-wait';
            }
        }, 5000);
    }
}

// Start real-time updates
setTimeout(simulateRealTimeUpdates, 2000);

