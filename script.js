// Google Translate API function
async function translateText(text, targetLang) {
    if (targetLang === 'ar' || targetLang === 'en') {
        return translations[targetLang][text] || text;
    }
    
    try {
        const response = await fetch(`https://translate.googleapis.com/translate_a/single?client=gtx&sl=en&tl=${targetLang}&dt=t&q=${encodeURIComponent(text)}`);
        const data = await response.json();
        return data[0][0][0] || text;
    } catch (error) {
        console.error('Translation error:', error);
        return text;
    }
}

// Translate page function
async function translatePage() {
    const selectedLang = document.getElementById('languageSelect').value;
    const elementsToTranslate = document.querySelectorAll('[data-translate]');
    const placeholdersToTranslate = document.querySelectorAll('[data-translate-placeholder]');
    
    // Show loading indicator
    document.body.style.cursor = 'wait';
    
    // Update direction for RTL languages
    const rtlLanguages = ['ar', 'he', 'fa', 'ur'];
    if (rtlLanguages.includes(selectedLang)) {
        document.documentElement.setAttribute('dir', 'rtl');
        document.documentElement.setAttribute('lang', selectedLang);
    } else {
        document.documentElement.setAttribute('dir', 'ltr');
        document.documentElement.setAttribute('lang', selectedLang);
    }
    
    // Translate elements
    for (const element of elementsToTranslate) {
        const key = element.getAttribute('data-translate');
        const originalText = translations.en[key] || element.textContent;
        
        if (selectedLang === 'ar' || selectedLang === 'en') {
            element.textContent = translations[selectedLang][key] || originalText;
        } else {
            try {
                const translatedText = await translateText(originalText, selectedLang);
                element.textContent = translatedText;
            } catch (error) {
                console.error('Translation failed for:', key, error);
            }
        }
    }
    
    // Translate placeholders
    for (const element of placeholdersToTranslate) {
        const key = element.getAttribute('data-translate-placeholder');
        const originalText = translations.en[key] || element.placeholder;
        
        if (selectedLang === 'ar' || selectedLang === 'en') {
            element.placeholder = translations[selectedLang][key] || originalText;
        } else {
            try {
                const translatedText = await translateText(originalText, selectedLang);
                element.placeholder = translatedText;
            } catch (error) {
                console.error('Translation failed for placeholder:', key, error);
            }
        }
    }
    
    // Remove loading indicator
    document.body.style.cursor = 'default';
    
    // Save language preference
    localStorage.setItem('preferredLanguage', selectedLang);
}

